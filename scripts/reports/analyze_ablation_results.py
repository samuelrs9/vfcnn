#!/usr/bin/env python3
"""
Script to analyze ablation study results and generate comparison reports.
"""

import argparse
import os
from pathlib import Path

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns


def parse_args():
    parser = argparse.ArgumentParser(
        description="Analyze ablation study timing results"
    )
    parser.add_argument(
        "timing_csv",
        help="Path to the timing_results.csv file generated by run_ablation_study.sh"
    )
    parser.add_argument(
        "--output-dir",
        "-o",
        default=None,
        help="Output directory for plots and reports (default: same as input CSV)"
    )
    return parser.parse_args()


def load_timing_data(csv_path):
    """Load timing results from CSV file."""
    df = pd.read_csv(csv_path)
    
    # Ensure duration is numeric
    df['duration_seconds'] = pd.to_numeric(df['duration_seconds'], errors='coerce')
    
    # Ensure particle count is numeric
    if 'num_particles' in df.columns:
        df['num_particles'] = pd.to_numeric(df['num_particles'], errors='coerce')
        df['frames_processed'] = pd.to_numeric(df['frames_processed'], errors='coerce')
        
        # Calculate time per million particles
        df['time_per_million_particles'] = (df['duration_seconds'] / df['num_particles']) * 1e6
        
        # Calculate average time per frame
        df['time_per_frame'] = df['duration_seconds'] / df['frames_processed']
    else:
        df['num_particles'] = 0
        df['frames_processed'] = 0
        df['time_per_million_particles'] = 0
        df['time_per_frame'] = 0
    
    # Ensure GPU metrics are numeric
    if 'avg_gpu_util' in df.columns:
        df['avg_gpu_util'] = pd.to_numeric(df['avg_gpu_util'], errors='coerce')
        df['max_gpu_util'] = pd.to_numeric(df['max_gpu_util'], errors='coerce')
        df['avg_gpu_mem'] = pd.to_numeric(df['avg_gpu_mem'], errors='coerce')
        df['max_gpu_mem'] = pd.to_numeric(df['max_gpu_mem'], errors='coerce')
    else:
        df['avg_gpu_util'] = 0
        df['max_gpu_util'] = 0
        df['avg_gpu_mem'] = 0
        df['max_gpu_mem'] = 0
    
    return df


def generate_summary_statistics(df):
    """Generate summary statistics grouped by task type."""
    summary = df.groupby('task').agg({
        'time_per_million_particles': ['mean', 'std', 'min', 'max'],
        'avg_gpu_util': ['mean', 'std', 'min', 'max'],
        'avg_gpu_mem': ['mean', 'std', 'min', 'max'],
        'num_particles': 'sum',
        'frames_processed': 'sum',
        'duration_seconds': 'count'
    }).reset_index()
    
    # Flatten column names
    summary.columns = ['_'.join(col).strip('_') for col in summary.columns.values]
    summary = summary.round(4)
    
    return summary


def generate_detailed_table(df):
    """Generate detailed table with all results."""
    detailed = df.pivot_table(
        index='simulation',
        columns='task',
        values='duration_seconds',
        aggfunc='mean'
    ).reset_index()
    
    detailed = detailed.round(2)
    return detailed


def plot_task_comparison(df, output_dir):
    """Create bar plots comparing time per million particles and GPU usage."""
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 6))
    
    # Plot 1: Time per million particles
    summary_normalized = df.groupby('task')['time_per_million_particles'].mean().sort_values()
    summary_normalized.plot(kind='bar', color=['#2E86AB', '#A23B72', '#F18F01'], ax=ax1)
    ax1.set_title('Average Time per Million Particles', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Task Type', fontsize=12)
    ax1.set_ylabel('Time (seconds / 1M particles)', fontsize=12)
    ax1.tick_params(axis='x', rotation=45)
    ax1.grid(axis='y', alpha=0.3)
    
    # Add value labels on bars
    for i, v in enumerate(summary_normalized):
        ax1.text(i, v + max(summary_normalized)*0.02, f'{v:.2f}s', 
                ha='center', va='bottom', fontweight='bold')
    
    # Plot 2: Average GPU utilization
    summary_gpu = df.groupby('task')['avg_gpu_util'].mean().sort_values()
    summary_gpu.plot(kind='bar', color=['#2E86AB', '#A23B72', '#F18F01'], ax=ax2)
    ax2.set_title('Average GPU Utilization', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Task Type', fontsize=12)
    ax2.set_ylabel('GPU Utilization (%)', fontsize=12)
    ax2.tick_params(axis='x', rotation=45)
    ax2.grid(axis='y', alpha=0.3)
    
    # Add value labels on bars
    for i, v in enumerate(summary_gpu):
        ax2.text(i, v + max(summary_gpu)*0.02, f'{v:.1f}%', 
                ha='center', va='bottom', fontweight='bold')
    
    plt.tight_layout()
    
    output_path = os.path.join(output_dir, 'task_comparison.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved plot: {output_path}")
    plt.close()


