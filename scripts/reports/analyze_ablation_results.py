def plot_heatmap(df, output_dir):
    """Create heatmaps of normalized time and GPU usage."""
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 8))
    
    # Heatmap 1: Time per million particles
    pivot_normalized = df.pivot_table(
        index='simulation',
        columns='task',
        values='time_per_million_particles',
        aggfunc='mean'
    )
    
    sns.heatmap(pivot_normalized, annot=True, fmt='.2f', cmap='YlOrRd', 
                cbar_kws={'label': 'Time (s / 1M particles)'}, ax=ax1)
    ax1.set_title('Time per Million Particles', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Task Type', fontsize=12)
    ax1.set_ylabel('Simulation', fontsize=12)
    
    # Heatmap 2: GPU utilization
    pivot_gpu = df.pivot_table(
        index='simulation',
        columns='task',
        values='avg_gpu_util',
        aggfunc='mean'
    )
    
    sns.heatmap(pivot_gpu, annot=True, fmt='.1f', cmap='YlGnBu', 
                cbar_kws={'label': 'GPU Utilization (%)'}, ax=ax2)
    ax2.set_title('Average GPU Utilization', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Task Type', fontsize=12)
    ax2.set_ylabel('Simulation', fontsize=12)
    
    plt.tight_layout()
    
    output_path = os.path.join(output_dir, 'heatmap.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved plot: {output_path}")
    plt.close()


def calculate_speedup(df):
    """Calculate speedup of parallel execution vs sequential execution."""
    
    # Get average time per million particles for each task
    task_means = df.groupby('task')['time_per_million_particles'].mean()
    
    # Get average GPU utilization for each task
    task_gpu = df.groupby('task')['avg_gpu_util'].mean()
    
    # Check if all required tasks exist
    required_tasks = ['boundary_only', 'normal_only', 'boundary_normal']
    if not all(task in task_means.index for task in required_tasks):
        print(f"Warning: Not all required tasks found in results")
        return pd.DataFrame()
    
    # Sequential execution time = boundary_only + normal_only
    sequential_time = task_means['boundary_only'] + task_means['normal_only']
    sequential_gpu = (task_gpu['boundary_only'] + task_gpu['normal_only']) / 2
    
    # Parallel execution time = boundary_normal
    parallel_time = task_means['boundary_normal']
    parallel_gpu = task_gpu['boundary_normal']
    
    # Calculate speedup
    speedup_factor = sequential_time / parallel_time
    
    speedup = pd.DataFrame([
        {
            'execution_mode': 'Sequential (boundary + normal)',
            'time_per_1M_particles': sequential_time,
            'avg_gpu_util': sequential_gpu,
            'speedup': 1.0
        },
        {
            'execution_mode': 'Parallel (boundary+normal)',
            'time_per_1M_particles': parallel_time,
            'avg_gpu_util': parallel_gpu,
            'speedup': speedup_factor
        }
    ])
    
    speedup = speedup.round(3)
    return speedup


def generate_markdown_report(df, summary_stats, detailed_table, speedup, output_dir):
    """Generate a markdown report with all results."""
    report_path = os.path.join(output_dir, 'ablation_study_report.md')
    
    with open(report_path, 'w') as f:
        f.write("# Ablation Study Results\n\n")
        f.write(f"**Total experiments:** {len(df)}\n\n")
        f.write(f"**Simulations tested:** {df['simulation'].nunique()}\n\n")
        f.write(f"**Task types:** {', '.join(df['task'].unique())}\n\n")
        f.write(f"**Total particles processed:** {df['num_particles'].sum():,.0f}\n\n")
        f.write(f"**Total frames processed:** {df['frames_processed'].sum():.0f}\n\n")
        
        f.write("## Summary Statistics\n\n")
        f.write(summary_stats.to_markdown(index=False))
        f.write("\n\n")
        
        f.write("## Performance Metrics by Simulation\n\n")
        
        # Normalized time table
        f.write("### Time per Million Particles (seconds / 1M particles)\n\n")
        pivot_normalized = df.pivot_table(
            index='simulation',
            columns='task',
            values='time_per_million_particles',
            aggfunc='mean'
        ).round(2).reset_index()
        f.write(pivot_normalized.to_markdown(index=False))
        f.write("\n\n")
        
        # GPU utilization table
        f.write("### Average GPU Utilization (%)\n\n")
        pivot_gpu = df.pivot_table(
            index='simulation',
            columns='task',
            values='avg_gpu_util',
            aggfunc='mean'
        ).round(1).reset_index()
        f.write(pivot_gpu.to_markdown(index=False))
        f.write("\n\n")
        
        if not speedup.empty:
            f.write("## Parallel vs Sequential Execution\n\n")
            f.write("Comparison of parallel execution (boundary+normal simultaneously) ")
            f.write("vs sequential execution (boundary then normal separately):\n\n")
            f.write(speedup.to_markdown(index=False))
            f.write("\n\n")
            
            if len(speedup) >= 2:
                speedup_value = speedup.iloc[1]['speedup']
                f.write(f"**Speedup factor:** {speedup_value:.2f}x\n\n")
                f.write(f"Parallel execution is **{speedup_value:.2f}x faster** than sequential execution.\n\n")
        
        f.write("## Visualizations\n\n")
        f.write("- [Task Comparison](task_comparison.png) - Time per 1M particles and GPU utilization\n")
        f.write("- [Simulation Comparison](simulation_comparison.png) - Comparison across simulations\n")
        f.write("- [Heatmap](heatmap.png) - Normalized time and GPU usage heatmaps\n\n")
        
        f.write("## Key Findings\n\n")
        
        # Analysis on normalized time
        task_means_normalized = df.groupby('task')['time_per_million_particles'].mean()
        most_efficient = task_means_normalized.idxmin()
        least_efficient = task_means_normalized.idxmax()
        
        f.write(f"### Efficiency Analysis (per 1M particles)\n\n")
        f.write(f"- **Most efficient task:** {most_efficient} "
                f"(avg: {task_means_normalized[most_efficient]:.2f}s/1M)\n")
        f.write(f"- **Least efficient task:** {least_efficient} "
                f"(avg: {task_means_normalized[least_efficient]:.2f}s/1M)\n\n")
        
        # GPU analysis
        task_gpu = df.groupby('task')['avg_gpu_util'].mean()
        highest_gpu = task_gpu.idxmax()
        lowest_gpu = task_gpu.idxmin()
        
        f.write(f"### GPU Utilization Analysis\n\n")
        f.write(f"- **Highest GPU usage:** {highest_gpu} "
                f"(avg: {task_gpu[highest_gpu]:.1f}%)\n")
        f.write(f"- **Lowest GPU usage:** {lowest_gpu} "
                f"(avg: {task_gpu[lowest_gpu]:.1f}%)\n\n")
        
        if not speedup.empty and len(speedup) >= 2:
            seq_time = speedup.iloc[0]['time_per_1M_particles']
            par_time = speedup.iloc[1]['time_per_1M_particles']
            seq_gpu = speedup.iloc[0]['avg_gpu_util']
            par_gpu = speedup.iloc[1]['avg_gpu_util']
            speedup_val = speedup.iloc[1]['speedup']
            
            f.write(f"### Parallel Execution Benefits\n\n")
            f.write(f"- **Sequential execution:** {seq_time:.2f}s/1M particles, {seq_gpu:.1f}% avg GPU\n")
            f.write(f"- **Parallel execution:** {par_time:.2f}s/1M particles, {par_gpu:.1f}% avg GPU\n")
            f.write(f"- **Time reduction:** {((1 - 1/speedup_val) * 100):.1f}%\n")
            f.write(f"- **GPU utilization improvement:** {(par_gpu - seq_gpu):.1f} percentage points\n")
    
    print(f"Saved report: {report_path}")


def main():
    args = parse_args()
    
    # Determine output directory
    output_dir = args.output_dir
    if output_dir is None:
        output_dir = os.path.dirname(args.timing_csv)
    
    os.makedirs(output_dir, exist_ok=True)
    
    print(f"Loading timing data from: {args.timing_csv}")
    df = load_timing_data(args.timing_csv)
    
    print(f"Loaded {len(df)} experiments")
    print(f"\nSimulations: {sorted(df['simulation'].unique())}")
    print(f"Tasks: {sorted(df['task'].unique())}")
    print(f"Total particles: {df['num_particles'].sum():,.0f}")
    print(f"Total frames: {df['frames_processed'].sum():.0f}")
    
    # Generate statistics
    print("\nGenerating summary statistics...")
    summary_stats = generate_summary_statistics(df)
    print(summary_stats)
    
    print("\nGenerating detailed tables...")
    detailed_table = generate_detailed_table(df)
    print(detailed_table)
    
    print("\nCalculating speedup factors...")
    speedup = calculate_speedup(df)
    if not speedup.empty:
        print(speedup)
    
    # Generate plots
    print("\nGenerating visualizations...")
    plot_task_comparison(df, output_dir)
    plot_simulation_comparison(df, output_dir)
    plot_heatmap(df, output_dir)
    
    # Generate markdown report
    print("\nGenerating markdown report...")
    generate_markdown_report(df, summary_stats, detailed_table, speedup, output_dir)
    
    # Save processed data
    summary_csv = os.path.join(output_dir, 'summary_statistics.csv')
    summary_stats.to_csv(summary_csv, index=False)
    print(f"Saved summary: {summary_csv}")
    
    detailed_csv = os.path.join(output_dir, 'detailed_results.csv')
    detailed_table.to_csv(detailed_csv, index=False)
    print(f"Saved detailed results: {detailed_csv}")
    
    print("\n✓ Analysis complete!")


if __name__ == "__main__":
    main()
