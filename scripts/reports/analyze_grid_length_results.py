#!/usr/bin/env python3
"""
Script to analyze grid_length ablation study results.
"""

import argparse
import os
from pathlib import Path

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns


def parse_args():
    parser = argparse.ArgumentParser(
        description="Analyze grid_length ablation study timing results"
    )
    parser.add_argument(
        "timing_csv",
        help="Path to the timing_results.csv file generated by run_grid_length_ablation.sh"
    )
    parser.add_argument(
        "--metrics-csv",
        default=None,
        help="Path to the accuracy_metrics.csv file (default: same dir as timing_csv)"
    )
    parser.add_argument(
        "--output-dir",
        "-o",
        default=None,
        help="Output directory for plots and reports (default: same as input CSV)"
    )
    return parser.parse_args()


def load_timing_data(csv_path):
    """Load timing results from CSV file."""
    df = pd.read_csv(csv_path)
    
    # Ensure duration is numeric
    df['duration_seconds'] = pd.to_numeric(df['duration_seconds'], errors='coerce')
    
    # Ensure particle count is numeric
    if 'num_particles' in df.columns:
        df['num_particles'] = pd.to_numeric(df['num_particles'], errors='coerce')
        df['frames_processed'] = pd.to_numeric(df['frames_processed'], errors='coerce')
        
        # Calculate time per million particles
        df['time_per_million_particles'] = (df['duration_seconds'] / df['num_particles']) * 1e6
        
        # Calculate average time per frame
        df['time_per_frame'] = df['duration_seconds'] / df['frames_processed']
    else:
        df['num_particles'] = 0
        df['frames_processed'] = 0
        df['time_per_million_particles'] = 0
        df['time_per_frame'] = 0
    
    # Ensure GPU metrics are numeric
    if 'avg_gpu_util' in df.columns:
        df['avg_gpu_util'] = pd.to_numeric(df['avg_gpu_util'], errors='coerce')
        df['max_gpu_util'] = pd.to_numeric(df['max_gpu_util'], errors='coerce')
        df['avg_gpu_mem'] = pd.to_numeric(df['avg_gpu_mem'], errors='coerce')
        df['max_gpu_mem'] = pd.to_numeric(df['max_gpu_mem'], errors='coerce')
    else:
        df['avg_gpu_util'] = 0
        df['max_gpu_util'] = 0
        df['avg_gpu_mem'] = 0
        df['max_gpu_mem'] = 0
    
    # Ensure grid_length is numeric
    df['grid_length'] = pd.to_numeric(df['grid_length'], errors='coerce')
    
    return df


def load_metrics_data(csv_path):
    """Load accuracy metrics from CSV file."""
    if not os.path.exists(csv_path):
        return None
    
    df = pd.read_csv(csv_path)
    
    # Ensure all metrics are numeric
    metric_cols = ['avg_recall', 'avg_precision', 'avg_tnr', 'avg_f1', 'avg_mcc', 'avg_combined_metric']
    for col in metric_cols:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')
    
    # Ensure grid_length is numeric
    df['grid_length'] = pd.to_numeric(df['grid_length'], errors='coerce')
    
    return df


def plot_grid_length_comparison(df, df_metrics, output_dir):
    """Create line plots comparing time and GPU usage vs grid_length."""
    # Determine if we have metrics
    has_metrics = df_metrics is not None and not df_metrics.empty
    
    if has_metrics:
        fig, ((ax1, ax2), (ax3, ax4)) = plt.subplots(2, 2, figsize=(18, 12))
    else:
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 6))
    
    # Plot 1: Time per million particles vs grid_length
    summary_time = df.groupby('grid_length')['time_per_million_particles'].agg(['mean', 'std']).reset_index()
    summary_time = summary_time.sort_values('grid_length')
    
    ax1.errorbar(summary_time['grid_length'], summary_time['mean'], 
                 yerr=summary_time['std'], marker='o', capsize=5, capthick=2,
                 linewidth=2, markersize=8)
    ax1.set_title('Time per Million Particles vs Grid Length', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Grid Length', fontsize=12)
    ax1.set_ylabel('Time (seconds / 1M particles)', fontsize=12)
    ax1.set_xscale('log')
    ax1.grid(True, alpha=0.3)
    
    # Add value labels
    for _, row in summary_time.iterrows():
        ax1.annotate(f'{row["mean"]:.2f}', 
                    xy=(row['grid_length'], row['mean']),
                    xytext=(0, 10), textcoords='offset points',
                    ha='center', fontsize=9)
    
    # Plot 2: GPU utilization vs grid_length
    summary_gpu = df.groupby('grid_length')['avg_gpu_util'].agg(['mean', 'std']).reset_index()
    summary_gpu = summary_gpu.sort_values('grid_length')
    
    ax2.errorbar(summary_gpu['grid_length'], summary_gpu['mean'],
                 yerr=summary_gpu['std'], marker='s', capsize=5, capthick=2,
                 linewidth=2, markersize=8, color='green')
    ax2.set_title('GPU Utilization vs Grid Length', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Grid Length', fontsize=12)
    ax2.set_ylabel('GPU Utilization (%)', fontsize=12)
    ax2.set_xscale('log')
    ax2.grid(True, alpha=0.3)
    
    # Add value labels
    for _, row in summary_gpu.iterrows():
        ax2.annotate(f'{row["mean"]:.1f}%', 
                    xy=(row['grid_length'], row['mean']),
                    xytext=(0, 10), textcoords='offset points',
                    ha='center', fontsize=9)
    
    # Plot 3 & 4: Accuracy metrics (if available)
    if has_metrics:
        # Plot 3: F1 Score vs grid_length
        summary_f1 = df_metrics.groupby('grid_length')['avg_f1'].agg(['mean', 'std']).reset_index()
        summary_f1 = summary_f1.sort_values('grid_length')
        
        ax3.errorbar(summary_f1['grid_length'], summary_f1['mean'],
                     yerr=summary_f1['std'], marker='d', capsize=5, capthick=2,
                     linewidth=2, markersize=8, color='blue')
        ax3.set_title('F1 Score vs Grid Length', fontsize=14, fontweight='bold')
        ax3.set_xlabel('Grid Length', fontsize=12)
        ax3.set_ylabel('F1 Score', fontsize=12)
        ax3.set_xscale('log')
        ax3.set_ylim([0.8, 1.0])
        ax3.grid(True, alpha=0.3)
        
        for _, row in summary_f1.iterrows():
            ax3.annotate(f'{row["mean"]:.3f}', 
                        xy=(row['grid_length'], row['mean']),
                        xytext=(0, 10), textcoords='offset points',
                        ha='center', fontsize=9)
        
        # Plot 4: MCC vs grid_length
        summary_mcc = df_metrics.groupby('grid_length')['avg_mcc'].agg(['mean', 'std']).reset_index()
        summary_mcc = summary_mcc.sort_values('grid_length')
        
        ax4.errorbar(summary_mcc['grid_length'], summary_mcc['mean'],
                     yerr=summary_mcc['std'], marker='^', capsize=5, capthick=2,
                     linewidth=2, markersize=8, color='purple')
        ax4.set_title('Matthews Correlation Coefficient vs Grid Length', fontsize=14, fontweight='bold')
        ax4.set_xlabel('Grid Length', fontsize=12)
        ax4.set_ylabel('MCC', fontsize=12)
        ax4.set_xscale('log')
        ax4.set_ylim([0.8, 1.0])
        ax4.grid(True, alpha=0.3)
        
        for _, row in summary_mcc.iterrows():
            ax4.annotate(f'{row["mean"]:.3f}', 
                        xy=(row['grid_length'], row['mean']),
                        xytext=(0, 10), textcoords='offset points',
                        ha='center', fontsize=9)
    
    plt.tight_layout()
    
    output_path = os.path.join(output_dir, 'grid_length_comparison.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved plot: {output_path}")
    plt.close()


def plot_simulation_comparison(df, output_dir):
    """Create grouped plots comparing grid_length across simulations."""
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(18, 7))
    
    # Plot 1: Time per million particles by simulation
    for sim in sorted(df['simulation'].unique()):
        sim_data = df[df['simulation'] == sim].sort_values('grid_length')
        ax1.plot(sim_data['grid_length'], sim_data['time_per_million_particles'], 
                marker='o', label=sim, linewidth=2, markersize=6)
    
    ax1.set_title('Time per Million Particles by Simulation', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Grid Length', fontsize=12)
    ax1.set_ylabel('Time (s / 1M particles)', fontsize=12)
    ax1.set_xscale('log')
    ax1.legend(bbox_to_anchor=(1.05, 1), loc='upper left')
    ax1.grid(True, alpha=0.3)
    
    # Plot 2: GPU utilization by simulation
    for sim in sorted(df['simulation'].unique()):
        sim_data = df[df['simulation'] == sim].sort_values('grid_length')
        ax2.plot(sim_data['grid_length'], sim_data['avg_gpu_util'], 
                marker='s', label=sim, linewidth=2, markersize=6)
    
    ax2.set_title('GPU Utilization by Simulation', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Grid Length', fontsize=12)
    ax2.set_ylabel('GPU Utilization (%)', fontsize=12)
    ax2.set_xscale('log')
    ax2.legend(bbox_to_anchor=(1.05, 1), loc='upper left')
    ax2.grid(True, alpha=0.3)
    
    plt.tight_layout()
    
    output_path = os.path.join(output_dir, 'simulation_comparison.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved plot: {output_path}")
    plt.close()


def plot_heatmap(df, output_dir):
    """Create heatmaps of time and GPU usage."""
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 8))
    
    # Heatmap 1: Time per million particles
    pivot_time = df.pivot_table(
        index='simulation',
        columns='grid_length',
        values='time_per_million_particles',
        aggfunc='mean'
    )
    
    sns.heatmap(pivot_time, annot=True, fmt='.2f', cmap='YlOrRd', 
                cbar_kws={'label': 'Time (s / 1M particles)'}, ax=ax1)
    ax1.set_title('Time per Million Particles', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Grid Length', fontsize=12)
    ax1.set_ylabel('Simulation', fontsize=12)
    
    # Heatmap 2: GPU utilization
    pivot_gpu = df.pivot_table(
        index='simulation',
        columns='grid_length',
        values='avg_gpu_util',
        aggfunc='mean'
    )
    
    sns.heatmap(pivot_gpu, annot=True, fmt='.1f', cmap='YlGnBu', 
                cbar_kws={'label': 'GPU Utilization (%)'}, ax=ax2)
    ax2.set_title('Average GPU Utilization', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Grid Length', fontsize=12)
    ax2.set_ylabel('Simulation', fontsize=12)
    
    plt.tight_layout()
    
    output_path = os.path.join(output_dir, 'heatmap.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved plot: {output_path}")
    plt.close()


def generate_markdown_report(df, df_metrics, output_dir):
    """Generate a markdown report with all results."""
    report_path = os.path.join(output_dir, 'grid_length_ablation_report.md')
    
    has_metrics = df_metrics is not None and not df_metrics.empty
    
    # Calculate summary statistics
    summary_stats = df.groupby('grid_length').agg({
        'time_per_million_particles': ['mean', 'std', 'min', 'max'],
        'avg_gpu_util': ['mean', 'std', 'min', 'max'],
        'num_particles': 'sum',
        'frames_processed': 'sum'
    }).round(2)
    
    with open(report_path, 'w') as f:
        f.write("# Grid Length Ablation Study Results\n\n")
        f.write(f"**Total experiments:** {len(df)}\n\n")
        f.write(f"**Simulations tested:** {df['simulation'].nunique()}\n\n")
        f.write(f"**Grid length values:** {sorted(df['grid_length'].unique())}\n\n")
        f.write(f"**Total particles processed:** {df['num_particles'].sum():,.0f}\n\n")
        f.write(f"**Total frames processed:** {df['frames_processed'].sum():.0f}\n\n")
        
        f.write("## Summary Statistics by Grid Length\n\n")
        f.write(summary_stats.to_markdown())
        f.write("\n\n")
        
        f.write("## Performance Metrics\n\n")
        
        # Time table
        f.write("### Time per Million Particles (seconds / 1M particles)\n\n")
        pivot_time = df.pivot_table(
            index='simulation',
            columns='grid_length',
            values='time_per_million_particles',
            aggfunc='mean'
        ).round(2).reset_index()
        f.write(pivot_time.to_markdown(index=False))
        f.write("\n\n")
        
        # GPU table
        f.write("### Average GPU Utilization (%)\n\n")
        pivot_gpu = df.pivot_table(
            index='simulation',
            columns='grid_length',
            values='avg_gpu_util',
            aggfunc='mean'
        ).round(1).reset_index()
        f.write(pivot_gpu.to_markdown(index=False))
        f.write("\n\n")
        
        # Accuracy metrics (if available)
        if has_metrics:
            f.write("## Accuracy Metrics\n\n")
            
            # F1 Score table
            f.write("### F1 Score\n\n")
            pivot_f1 = df_metrics.pivot_table(
                index='simulation',
                columns='grid_length',
                values='avg_f1',
                aggfunc='mean'
            ).round(4).reset_index()
            f.write(pivot_f1.to_markdown(index=False))
            f.write("\n\n")
            
            # MCC table
            f.write("### Matthews Correlation Coefficient (MCC)\n\n")
            pivot_mcc = df_metrics.pivot_table(
                index='simulation',
                columns='grid_length',
                values='avg_mcc',
                aggfunc='mean'
            ).round(4).reset_index()
            f.write(pivot_mcc.to_markdown(index=False))
            f.write("\n\n")
            
            # Recall table
            f.write("### Recall (TPR)\n\n")
            pivot_recall = df_metrics.pivot_table(
                index='simulation',
                columns='grid_length',
                values='avg_recall',
                aggfunc='mean'
            ).round(4).reset_index()
            f.write(pivot_recall.to_markdown(index=False))
            f.write("\n\n")
            
            # Precision table
            f.write("### Precision (PPV)\n\n")
            pivot_precision = df_metrics.pivot_table(
                index='simulation',
                columns='grid_length',
                values='avg_precision',
                aggfunc='mean'
            ).round(4).reset_index()
            f.write(pivot_precision.to_markdown(index=False))
            f.write("\n\n")
        
        f.write("## Visualizations\n\n")
        f.write("- [Grid Length Comparison](grid_length_comparison.png)\n")
        f.write("- [Simulation Comparison](simulation_comparison.png)\n")
        f.write("- [Heatmap](heatmap.png)\n\n")
        
        f.write("## Key Findings\n\n")
        
        # Find optimal grid length (lowest time per million particles)
        avg_time_by_gl = df.groupby('grid_length')['time_per_million_particles'].mean()
        optimal_gl = avg_time_by_gl.idxmin()
        worst_gl = avg_time_by_gl.idxmax()
        
        f.write(f"### Performance Analysis\n\n")
        f.write(f"- **Fastest grid length:** {optimal_gl} "
                f"(avg: {avg_time_by_gl[optimal_gl]:.2f}s/1M)\n")
        f.write(f"- **Slowest grid length:** {worst_gl} "
                f"(avg: {avg_time_by_gl[worst_gl]:.2f}s/1M)\n")
        f.write(f"- **Performance difference:** {avg_time_by_gl[worst_gl] / avg_time_by_gl[optimal_gl]:.2f}x\n\n")
        
        # GPU analysis
        avg_gpu_by_gl = df.groupby('grid_length')['avg_gpu_util'].mean()
        highest_gpu_gl = avg_gpu_by_gl.idxmax()
        lowest_gpu_gl = avg_gpu_by_gl.idxmin()
        
        f.write(f"### GPU Utilization Analysis\n\n")
        f.write(f"- **Highest GPU usage:** grid_length={highest_gpu_gl} "
                f"(avg: {avg_gpu_by_gl[highest_gpu_gl]:.1f}%)\n")
        f.write(f"- **Lowest GPU usage:** grid_length={lowest_gpu_gl} "
                f"(avg: {avg_gpu_by_gl[lowest_gpu_gl]:.1f}%)\n\n")
        
        # Accuracy analysis (if available)
        if has_metrics:
            avg_f1_by_gl = df_metrics.groupby('grid_length')['avg_f1'].mean()
            best_f1_gl = avg_f1_by_gl.idxmax()
            worst_f1_gl = avg_f1_by_gl.idxmin()
            
            avg_mcc_by_gl = df_metrics.groupby('grid_length')['avg_mcc'].mean()
            best_mcc_gl = avg_mcc_by_gl.idxmax()
            
            f.write(f"### Accuracy Analysis\n\n")
            f.write(f"- **Best F1 Score:** grid_length={best_f1_gl} "
                    f"(avg: {avg_f1_by_gl[best_f1_gl]:.4f})\n")
            f.write(f"- **Worst F1 Score:** grid_length={worst_f1_gl} "
                    f"(avg: {avg_f1_by_gl[worst_f1_gl]:.4f})\n")
            f.write(f"- **Best MCC:** grid_length={best_mcc_gl} "
                    f"(avg: {avg_mcc_by_gl[best_mcc_gl]:.4f})\n\n")
        
        f.write(f"### Recommendations\n\n")
        f.write(f"Based on the ablation study:\n\n")
        f.write(f"- **Best performance (speed):** grid_length={optimal_gl}\n")
        
        if has_metrics:
            f.write(f"- **Best accuracy (F1):** grid_length={best_f1_gl}\n")
            f.write(f"- **Best accuracy (MCC):** grid_length={best_mcc_gl}\n\n")
            
            # Check if there's a clear winner
            if optimal_gl == best_f1_gl == best_mcc_gl:
                f.write(f"**✓ Recommended grid_length: {optimal_gl}** - Best in both speed and accuracy\n\n")
            else:
                f.write(f"**Trade-off consideration:** Speed-optimal ({optimal_gl}) differs from accuracy-optimal ({best_f1_gl})\n\n")
        
        f.write(f"- Consider memory constraints and accuracy requirements when choosing grid_length\n")
        f.write(f"- Smaller grid_length values provide finer resolution but may be slower\n")
        f.write(f"- Larger grid_length values are faster but may reduce accuracy\n")
    
    print(f"Saved report: {report_path}")


def main():
    args = parse_args()
    
    # Determine output directory
    output_dir = args.output_dir
    if output_dir is None:
        output_dir = os.path.dirname(args.timing_csv)
    
    os.makedirs(output_dir, exist_ok=True)
    
    # Determine metrics CSV path
    metrics_csv = args.metrics_csv
    if metrics_csv is None:
        metrics_csv = os.path.join(os.path.dirname(args.timing_csv), 'accuracy_metrics.csv')
    
    print(f"Loading timing data from: {args.timing_csv}")
    df = load_timing_data(args.timing_csv)
    
    print(f"Loaded {len(df)} experiments")
    print(f"\nSimulations: {sorted(df['simulation'].unique())}")
    print(f"Grid lengths: {sorted(df['grid_length'].unique())}")
    print(f"Total particles: {df['num_particles'].sum():,.0f}")
    print(f"Total frames: {df['frames_processed'].sum():.0f}")
    
    # Load metrics data
    df_metrics = None
    if os.path.exists(metrics_csv):
        print(f"\nLoading accuracy metrics from: {metrics_csv}")
        df_metrics = load_metrics_data(metrics_csv)
        if df_metrics is not None and not df_metrics.empty:
            print(f"Loaded {len(df_metrics)} metric records")
            print(f"Average F1 Score: {df_metrics['avg_f1'].mean():.4f}")
            print(f"Average MCC: {df_metrics['avg_mcc'].mean():.4f}")
        else:
            print("WARNING: Metrics file exists but could not be loaded")
    else:
        print(f"\nWARNING: Accuracy metrics not found at {metrics_csv}")
        print("Analysis will proceed without accuracy metrics")
    
    # Generate plots
    print("\nGenerating visualizations...")
    plot_grid_length_comparison(df, df_metrics, output_dir)
    plot_simulation_comparison(df, output_dir)
    plot_heatmap(df, output_dir)
    
    # Generate markdown report
    print("\nGenerating markdown report...")
    generate_markdown_report(df, df_metrics, output_dir)
    
    # Save processed data
    summary_csv = os.path.join(output_dir, 'summary_by_grid_length.csv')
    summary = df.groupby('grid_length').agg({
        'time_per_million_particles': ['mean', 'std'],
        'avg_gpu_util': ['mean', 'std'],
        'duration_seconds': 'count'
    }).round(3)
    summary.to_csv(summary_csv)
    print(f"Saved summary: {summary_csv}")
    
    # Save metrics summary if available
    if df_metrics is not None and not df_metrics.empty:
        metrics_summary_csv = os.path.join(output_dir, 'accuracy_summary_by_grid_length.csv')
        metrics_summary = df_metrics.groupby('grid_length').agg({
            'avg_f1': ['mean', 'std'],
            'avg_mcc': ['mean', 'std'],
            'avg_recall': ['mean', 'std'],
            'avg_precision': ['mean', 'std']
        }).round(4)
        metrics_summary.to_csv(metrics_summary_csv)
        print(f"Saved metrics summary: {metrics_summary_csv}")
    
    print("\n✓ Analysis complete!")


if __name__ == "__main__":
    main()
